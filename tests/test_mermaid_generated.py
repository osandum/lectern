"""The flowchart and state parsers' generated tables are what their
sources make.

Each family's are generated by build-aux/mermaid/generate.py and
committed: the lexer from mermaid's compiled lexer as recorded in
mermaid_corpus/recorded/<family>-lexer.json, the parse table from
lectern/mermaid/<family>.lark with Lark. Editing either source without
regenerating fails here, as does moving the mermaid pin without
re-recording.
"""
import importlib.util
import json
import pathlib
import subprocess
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
CORPUS = ROOT / "tests" / "mermaid_corpus"


def generator():
    spec = importlib.util.spec_from_file_location(
        "generate", ROOT / "build-aux" / "mermaid" / "generate.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FAMILIES = ("flowchart", "state")


@pytest.mark.parametrize("family", FAMILIES)
def test_the_lexer_is_generated_from_the_recorded_mermaid_lexer(family):
    make, path = generator().target("lexer", family)
    assert path.read_text() == make(), "run build-aux/mermaid/generate.py lexer"


@pytest.mark.parametrize("family", FAMILIES)
def test_the_parse_table_is_generated_from_the_grammar(family):
    pytest.importorskip("lark", reason="Lark builds the table; pip install lark")
    make, path = generator().target("tables", family)
    assert path.read_text() == make(), "run build-aux/mermaid/generate.py tables"


def test_everything_recorded_comes_from_the_pinned_mermaid():
    pinned = json.loads((CORPUS / "record" / "package.json").read_text())["dependencies"]["mermaid"]
    for path in (CORPUS / "recorded").glob("*.json"):
        assert json.loads(path.read_text())["mermaid"] == pinned, path.name
    from lectern.mermaid import _flowchart_lexer, _state_lexer
    assert _flowchart_lexer.MERMAID == pinned
    assert _state_lexer.MERMAID == pinned


def test_the_tables_load_only_when_a_diagram_is_parsed():
    # The parsing machinery stays out of a launch that shows no diagram
    # (AGENTS.md's deferred-import rule), and so does the 100 KB table.
    code = ("import sys, lectern.mermaid, lectern.renderer; "
            "print(any(m.startswith(('lectern.mermaid._flowchart', 'lectern.mermaid._state')) "
            "for m in sys.modules))")
    out = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True,
                         cwd=ROOT, check=True)
    assert out.stdout.strip() == "False"
