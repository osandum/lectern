"""Only here to stamp build info into the package; everything else about
the project is in pyproject.toml. See lectern/buildinfo.py for why."""
import os
import sys
import time

from setuptools import setup
from setuptools.command.build_py import build_py

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lectern.buildinfo import archival_commit, git_commit  # noqa: E402


class build_py_with_info(build_py):
    def run(self):
        super().run()
        # An editable install runs build_py too, but its _build.py would be
        # frozen at install time and go stale with the next commit;
        # buildinfo.py asks git instead.
        if getattr(self, "editable_mode", False):
            return
        commit, dirty = git_commit(HERE)
        if not commit:
            commit = archival_commit(os.path.join(HERE, "lectern", "_archival.txt"))
        # SOURCE_DATE_EPOCH, when the packager sets it, keeps the build
        # reproducible: the same sources stamp the same time.
        epoch = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))
        built = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(epoch))
        target = os.path.join(self.build_lib, "lectern", "_build.py")
        with open(target, "w", encoding="utf-8") as f:
            f.write("# Generated by setup.py at build time.\n")
            f.write(f"COMMIT = {commit!r}\n")
            f.write(f"DIRTY = {dirty!r}\n")
            f.write(f"BUILT = {built!r}\n")


setup(cmdclass={"build_py": build_py_with_info})
